const createOrder = asyncHandler(async (req, res) => {
  const { shippingInfo, paymentInfo } = req.body;
  const { razorpayOrderId, razorpayPaymentId, razorpaySignature } = paymentInfo || {};
  const { verifyPaymentSignature, getRazorpayClient, getCartTotal } = require("./paymentCtrl");
  if (!verifyPaymentSignature(razorpayOrderId, razorpayPaymentId, razorpaySignature)) {
    return res.status(400).json({ message: "Payment verification failed." });
  }
  const existing = await Order.findOne({ "paymentInfo.razorpayPaymentId": razorpayPaymentId });
  if (existing) return res.status(409).json({ message: "Payment already used." });

  const cart = await Cart.find({ userId: req.user._id }).populate("productId");
  const totalPrice = getCartTotal(cart);
  if (!totalPrice) return res.status(400).json({ message: "Your cart is empty." });

  const client = getRazorpayClient();
  const payment = await client.payments.fetch(razorpayPaymentId);
  const expectedAmount = Math.round((totalPrice + 100) * 100);
  if (payment.order_id !== razorpayOrderId || payment.status !== "captured" ||
      payment.currency !== "INR" || payment.amount !== expectedAmount) {
    return res.status(400).json({ message: "Payment amount or status is invalid." });
  }
  const order = await Order.create({
    user: req.user._id,
    shippingInfo,
    orderItems: cart.map(({ productId, color, quantity }) => ({
      product: productId._id,
      color,
      quantity,
      price: productId.price,
    })),
    totalPrice,
    totalPriceAfterDiscount: totalPrice + 100,
    paymentInfo: { razorpayOrderId, razorpayPaymentId },
  });
  await Cart.deleteMany({ userId: req.user._id });
  res.status(201).json({ order, success: true });
});

